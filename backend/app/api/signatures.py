import base64
from typing import List, Optional
from fastapi import APIRouter, Depends, HTTPException, status, Request
from pydantic import BaseModel
from sqlalchemy.orm import Session
from cryptography.hazmat.primitives import hashes, serialization
from cryptography.hazmat.primitives.asymmetric import padding
from cryptography.hazmat.backends import default_backend

from backend.app.database import get_db
from backend.app.models.user import User
from backend.app.models.file import EncryptedFile
from backend.app.models.signature import DocumentSignature
from backend.app.models.permission import FilePermission
from backend.app.security.auth import get_current_user
from backend.app.security.audit_logger import log_audit_event

router = APIRouter(prefix="/api/files", tags=["e-Signatures"])


class SignRequest(BaseModel):
    signing_private_key: str  # PEM


@router.post("/{file_id}/sign", status_code=status.HTTP_201_CREATED)
def sign_document(
    file_id: str,
    req: SignRequest,
    request: Request,
    current_user: User = Depends(get_current_user),
    db: Session = Depends(get_db)
):
    file = db.query(EncryptedFile).filter(
        EncryptedFile.id == file_id,
        EncryptedFile.is_deleted == False
    ).first()
    if not file:
        raise HTTPException(status_code=404, detail="File not found.")

    # Must be owner or have valid read permission
    is_owner = (file.owner_id == current_user.id)
    if not is_owner:
        perm = db.query(FilePermission).filter(
            FilePermission.file_id == file_id,
            FilePermission.recipient_id == current_user.id,
            FilePermission.is_revoked == False
        ).first()
        if not perm or not perm.can_read:
            raise HTTPException(status_code=403, detail="No read permission to sign this document.")

    # Sign using RSA-PSS over file's SHA-256 hash
    try:
        private_key = serialization.load_pem_private_key(
            req.signing_private_key.encode("utf-8"),
            password=None,
            backend=default_backend()
        )
        hash_bytes = bytes.fromhex(file.file_sha256_hash)
        signature = private_key.sign(
            hash_bytes,
            padding.PSS(mgf=padding.MGF1(hashes.SHA256()), salt_length=padding.PSS.MAX_LENGTH),
            hashes.SHA256()
        )
        sig_b64 = base64.b64encode(signature).decode("utf-8")

        # Verify key belongs to user if public key is registered
        if current_user.signing_public_key:
            pub_key = private_key.public_key()
            pub_pem = pub_key.public_bytes(
                serialization.Encoding.PEM,
                serialization.PublicFormat.SubjectPublicKeyInfo
            ).decode("utf-8").strip()
            registered_pem = current_user.signing_public_key.strip()
            if pub_pem != registered_pem:
                raise HTTPException(
                    status_code=400,
                    detail="Provided signing private key does not match your registered signing public key."
                )
    except HTTPException:
        raise
    except Exception as e:
        raise HTTPException(status_code=400, detail=f"Cryptographic signing failed: {str(e)}")

    sig = DocumentSignature(
        file_id=file_id,
        signer_id=current_user.id,
        signer_username=current_user.username,
        signature_b64=sig_b64,
        signed_hash=file.file_sha256_hash,
        algorithm="RSA-PSS-SHA256",
        is_valid="VALID"
    )
    db.add(sig)
    db.commit()
    db.refresh(sig)

    log_audit_event(
        db=db,
        action="DOCUMENT_SIGNED",
        status="SUCCESS",
        user_id=current_user.id,
        username=current_user.username,
        resource_id=file.id,
        resource_name=file.original_filename,
        details=f"RSA-PSS digital signature generated by '{current_user.username}'.",
        ip_address=request.client.host if request.client else None,
        user_agent=request.headers.get("user-agent")
    )

    return {
        "id": sig.id,
        "file_id": sig.file_id,
        "signer_username": sig.signer_username,
        "signature_b64": sig.signature_b64[:32] + "...",
        "signed_hash": sig.signed_hash,
        "algorithm": sig.algorithm,
        "is_valid": sig.is_valid,
        "signed_at": sig.signed_at.isoformat()
    }


@router.get("/{file_id}/signatures")
def list_signatures(
    file_id: str,
    current_user: User = Depends(get_current_user),
    db: Session = Depends(get_db)
):
    file = db.query(EncryptedFile).filter(
        EncryptedFile.id == file_id,
        EncryptedFile.is_deleted == False
    ).first()
    if not file:
        raise HTTPException(status_code=404, detail="File not found.")

    is_owner = (file.owner_id == current_user.id)
    if not is_owner:
        perm = db.query(FilePermission).filter(
            FilePermission.file_id == file_id,
            FilePermission.recipient_id == current_user.id,
            FilePermission.is_revoked == False
        ).first()
        if not perm:
            raise HTTPException(status_code=403, detail="Access denied.")

    sigs = db.query(DocumentSignature).filter(
        DocumentSignature.file_id == file_id
    ).order_by(DocumentSignature.signed_at.desc()).all()

    return [
        {
            "id": s.id,
            "file_id": s.file_id,
            "signer_username": s.signer_username,
            "signature_b64": s.signature_b64[:32] + "...",
            "signed_hash": s.signed_hash,
            "algorithm": s.algorithm,
            "is_valid": s.is_valid,
            "signed_at": s.signed_at.isoformat()
        }
        for s in sigs
    ]


@router.get("/{file_id}/signatures/{sig_id}/verify")
def verify_signature(
    file_id: str,
    sig_id: int,
    current_user: User = Depends(get_current_user),
    db: Session = Depends(get_db)
):
    sig = db.query(DocumentSignature).filter(
        DocumentSignature.id == sig_id,
        DocumentSignature.file_id == file_id
    ).first()
    if not sig:
        raise HTTPException(status_code=404, detail="Signature record not found.")

    signer = db.query(User).filter(User.id == sig.signer_id).first()
    if not signer or not signer.signing_public_key:
        return {
            "valid": False,
            "signer": sig.signer_username,
            "message": "Signer public key not found or unavailable."
        }

    try:
        pub_key = serialization.load_pem_public_key(
            signer.signing_public_key.encode("utf-8"),
            backend=default_backend()
        )
        hash_bytes = bytes.fromhex(sig.signed_hash)
        sig_bytes = base64.b64decode(sig.signature_b64)
        pub_key.verify(
            sig_bytes,
            hash_bytes,
            padding.PSS(mgf=padding.MGF1(hashes.SHA256()), salt_length=padding.PSS.MAX_LENGTH),
            hashes.SHA256()
        )
        return {
            "valid": True,
            "signer": sig.signer_username,
            "signed_at": sig.signed_at.isoformat(),
            "algorithm": sig.algorithm,
            "message": "Signature is cryptographically authentic and valid."
        }
    except Exception as e:
        return {
            "valid": False,
            "signer": sig.signer_username,
            "message": f"Cryptographic verification failed: {str(e)}"
        }
